def main():
    con = sqlite3.connect(DB)
    cur = con.cursor()

    # ---- 1. 添加 etiology 列 ----
    cols = [r[1] for r in cur.execute("PRAGMA table_info(syndromes)")]
    if "etiology" not in cols:
        cur.execute("ALTER TABLE syndromes ADD COLUMN etiology TEXT")
        print("已添加 etiology 列")
    else:
        print("etiology 列已存在")

    # ---- 2. 更新每条记录的病因 ----
    updated = 0
    for sid, etiology_text in ETIOLOGY.items():
        cur.execute("UPDATE syndromes SET etiology=? WHERE id=?", (etiology_text, sid))
        if cur.rowcount:
            updated += 1
    print(f"病因更新: {updated} 条")

    # ---- 3. 确认所有记录都有病因（检查是否存在缺失） ----
    missing = cur.execute("SELECT id, name FROM syndromes WHERE etiology IS NULL OR TRIM(etiology)=''").fetchall()
    if missing:
        print(f"警告: 以下{len(missing)}条记录缺少病因:")
        for m in missing:
            print(f"  {m['id']}: {m['name']}")
    else:
        print("所有辨证均已添加病因 ✓")

    con.commit()
    con.close()

    # ---- 4. 复制到 public/ ----
    shutil.copy2(DB, PUBLIC_DB)
    print(f"已复制 {DB} -> {PUBLIC_DB}")

    print("\n完成！请运行以下命令完成后续步骤：")
    print("  python3 scripts/export_json_backup.py")
    print("  python3 scripts/clean_data.py")
    print("  python3 scripts/check_sqlite.py")


if __name__ == "__main__":
    main()
