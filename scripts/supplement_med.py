def classify(name, category, eff_text):
    if name in NAME_OVERRIDE:
        v = NAME_OVERRIDE[name]
        if v and "??" not in v:
            return v
    if category in RULES:
        for sub, kws in RULES[category]:
            for k in kws:
                if k in eff_text:
                    return sub
    return None

todo = []
unmatched = []
rows = cur.execute("SELECT m.id,m.name,m.category,m.subcategory FROM medicines m").fetchall()
for r in rows:
    if r["subcategory"] and r["subcategory"].strip():
        continue
    cat = r["category"] or ""
    eff = cur.execute("SELECT value FROM medicines_effects WHERE parent_id=?", (r["id"],)).fetchall()
    eff_text = " ".join(x["value"] for x in eff)
    sub = classify(r["name"], cat, eff_text)
    if sub:
        todo.append((r["id"], r["name"], cat, sub))
    elif cat in RULES:
        unmatched.append((r["id"], r["name"], cat, eff_text[:40]))

print(f"可自动补全: {len(todo)} 条")
print(f"未命中(需人工/名称覆盖): {len(unmatched)} 条")
for i, n, c, e in unmatched:
    print(f"  未命中 {i} {n} [{c}] eff={e}")

if APPLY:
    for i, n, c, s in todo:
        cur.execute("UPDATE medicines SET subcategory=? WHERE id=?", (s, i))
    con.commit()
    print(f"\n已写入 {len(todo)} 条。")
else:
    print("\n(dry-run) 加 --apply 执行写入。")
con.close()
